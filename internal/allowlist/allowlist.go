// Package allowlist parses DaoCloud public mirror sources and renders Go data.
package allowlist

import (
	"bytes"
	"fmt"
	"io"
	"net/http"
	"sort"
	"strings"
	"time"
)

// RawBaseURL is the raw GitHub base URL for DaoCloud public-image-mirror.
const RawBaseURL = "https://raw.githubusercontent.com/DaoCloud/public-image-mirror"

// Data is the generated registry data.
type Data struct {
	Ref          string
	Replacements map[string]string
	Supported    map[string]struct{}
}

// Fetch downloads and parses official sources at the given git ref.
func Fetch(ref string) (Data, error) {
	allows, err := fetchText(RawBaseURL + "/" + ref + "/allows.txt")
	if err != nil {
		return Data{}, err
	}
	readme, err := fetchText(RawBaseURL + "/" + ref + "/README.md")
	if err != nil {
		return Data{}, err
	}

	data := Build(allows, readme, ref)
	if len(data.Replacements) == 0 {
		return Data{}, fmt.Errorf("no replacements parsed from README")
	}
	if len(data.Supported) == 0 {
		return Data{}, fmt.Errorf("no registries parsed from allows.txt")
	}
	return data, nil
}

func fetchText(url string) (string, error) {
	client := http.Client{Timeout: 20 * time.Second}
	response, err := client.Get(url)
	if err != nil {
		return "", err
	}
	defer response.Body.Close()
	if response.StatusCode != http.StatusOK {
		return "", fmt.Errorf("GET %s: %s", url, response.Status)
	}
	body, err := io.ReadAll(response.Body)
	if err != nil {
		return "", err
	}
	return string(body), nil
}

// ParseAllowsTxt extracts registry hosts from official allows.txt.
func ParseAllowsTxt(content string) []string {
	seen := map[string]struct{}{}
	for _, raw := range strings.Split(content, "\n") {
		line := strings.TrimSpace(raw)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		host := line
		if index := strings.IndexAny(host, "/ \t"); index >= 0 {
			host = host[:index]
		}
		host = strings.Trim(strings.TrimSpace(host), "`")
		if host == "" || strings.HasPrefix(host, "*") {
			continue
		}
		if !strings.Contains(host, ".") && host != "localhost" {
			continue
		}
		seen[host] = struct{}{}
	}
	return sortedKeys(seen)
}

// ParseReplacements extracts the official registry prefix replacement table.
func ParseReplacements(content string) map[string]string {
	result := map[string]string{}
	inSection := false
	for _, raw := range strings.Split(content, "\n") {
		line := strings.TrimSpace(raw)
		if strings.HasPrefix(line, "## ") {
			if inSection {
				break
			}
			inSection = strings.Contains(line, "支持前缀替换的 Registry")
			continue
		}
		if !inSection || !strings.HasPrefix(line, "|") {
			continue
		}
		fields := strings.Split(line, "|")
		if len(fields) < 4 {
			continue
		}
		source := cleanCell(fields[1])
		target := cleanCell(fields[2])
		if !strings.Contains(source, ".") || !strings.HasSuffix(target, ".m.daocloud.io") {
			continue
		}
		result[source] = target
	}
	return result
}

func cleanCell(cell string) string {
	return strings.TrimSpace(strings.Trim(cell, "` "))
}

// Build combines allows.txt and README data into generated registry data.
func Build(allowsContent string, readmeContent string, ref string) Data {
	replacements := ParseReplacements(readmeContent)
	supported := map[string]struct{}{}
	for _, host := range ParseAllowsTxt(allowsContent) {
		supported[host] = struct{}{}
	}
	for source := range replacements {
		supported[source] = struct{}{}
	}
	return Data{Ref: ref, Replacements: replacements, Supported: supported}
}

// RenderGo renders the generated imageref data file.
func RenderGo(data Data) string {
	var output bytes.Buffer
	fmt.Fprintln(&output, "// Code generated by go generate; DO NOT EDIT.")
	fmt.Fprintf(&output, "// Allows: %s/%s/allows.txt\n", RawBaseURL, data.Ref)
	fmt.Fprintf(&output, "// Replacements: %s/%s/README.md\n", RawBaseURL, data.Ref)
	fmt.Fprintln(&output)
	fmt.Fprintln(&output, "package imageref")
	fmt.Fprintln(&output)
	fmt.Fprintln(&output, "var replacements = map[string]string{")
	for _, source := range sortedKeys(data.Replacements) {
		fmt.Fprintf(&output, "\t%q: %q,\n", source, data.Replacements[source])
	}
	fmt.Fprintln(&output, "}")
	fmt.Fprintln(&output)
	fmt.Fprintln(&output, "var supported = map[string]struct{}{")
	for _, host := range sortedKeys(data.Supported) {
		fmt.Fprintf(&output, "\t%q: {},\n", host)
	}
	fmt.Fprintln(&output, "}")
	return output.String()
}

func sortedKeys[T any](values map[string]T) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}
